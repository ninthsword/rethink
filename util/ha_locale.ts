/**
 * Korean labels back to the values the appliances use.
 *
 * Several English values share a label — LOW, low and LIGHT are all 약 — so a label that
 * more than one value produces is left out entirely. Guessing one of them would send an
 * appliance a value from a different entity. This map is only a fallback anyway: a
 * writable enum is translated through the per-topic map that publishConfig builds, which
 * knows exactly which values that one entity offers.
 */
const KOREAN_VALUES_REVERSE = (() => {
    const sources: Record<string, string[]> = {}
    for (const [english, korean] of Object.entries(KOREAN_VALUES)) (sources[korean] ??= []).push(english)
    return Object.fromEntries(
        Object.entries(sources)
            .filter(([, english]) => english.length === 1)
            .map(([korean, english]) => [korean, english[0]]),
    )
})()

export function localizeValue(value: string, language: HALanguage | undefined): string {
    if (language !== 'korean' || HA_PROTOCOL_VALUES.has(value)) return value
    return KOREAN_VALUES[value] ?? value
}

export function delocalizeValue(value: string, language: HALanguage | undefined): string {
    if (language !== 'korean') return value
    return KOREAN_VALUES_REVERSE[value] ?? value
}

export function localizeDiscovery(config: DeviceDiscovery, language: HALanguage | undefined): DeviceDiscovery {
    if (language !== 'korean') return config

    const clone = JSON.parse(JSON.stringify(config)) as DeviceDiscovery & Record<string, unknown>
    for (const component of Object.values(clone.components) as Array<Record<string, unknown>>) {
        if (typeof component.name === 'string') {
            if (component.name === 'Power' && component.device_class === 'power') component.name = '소비 전력'
            else component.name = KOREAN_NAMES[component.name] ?? component.name
        }
        for (const key of ['options', 'fan_modes', 'swing_modes', 'swing_horizontal_modes', 'preset_modes', 'modes']) {
            // A climate entity's modes are Home Assistant's own HVAC modes, not labels:
            // it accepts only off/auto/cool/heat/dry/fan_only/heat_cool there and drops
            // anything else, which is how translating them took the "off" option away and
            // left the appliance impossible to turn off from the thermostat card. Every
            // other list here is free text that the appliance and Rethink agree on, and a
            // humidifier's modes are our own names, so those still get translated.
            if (key === 'modes' && component.platform === 'climate') continue
            if (Array.isArray(component[key]))
                component[key] = (component[key] as unknown[]).map((value) =>
                    typeof value === 'string'
                        ? value === 'auto'
                            ? '자동'
                            : value === 'on'
                              ? '켜짐'
                              : value === 'off'
                                ? '꺼짐'
                                : localizeValue(value, language)
                        : value,
                )
        }
    }
    if (typeof clone.device.name === 'string') clone.device.name = KOREAN_NAMES[clone.device.name] ?? clone.device.name
    return clone
}
